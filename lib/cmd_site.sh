site_documents() {
  local target="$1"
  local file any=0

  echo "<h2>Documents</h2>"
  echo "<ul>"
  for file in RETURN.md brief.md index.md; do
    if [[ -f "$target/$file" ]]; then
      echo "<li><a href=\"../$file\"><code>$file</code></a></li>"
      any=1
    fi
  done
  if [[ -f "$target/kit/kit.md" ]]; then
    echo "<li><a href=\"../kit/kit.md\"><code>kit/kit.md</code></a> -- the neutral kit every artefact imports</li>"
    any=1
  fi
  if [[ "$any" -eq 0 ]]; then
    echo "<li class=\"empty\">none yet</li>"
  fi
  echo "</ul>"
}

site_assets() {
  local target="$1"
  local slug spec dir count=0

  echo "<h2>Assets</h2>"
  echo "<table>"
  echo "<thead><tr><th>slug</th><th>name</th><th>form</th><th>status</th>"
  echo "<th>blanks</th><th>coverage</th><th>artefacts</th></tr></thead>"
  echo "<tbody>"

  while IFS= read -r slug; do
    if [[ -z "$slug" ]]; then continue; fi
    dir="$(drop_asset_dir "$target" "$slug")"

    echo "<tr>"
    echo "<td><code>$slug</code></td>"

    if spec="$(drop_spec_path "$target" "$slug")"; then
      echo "<td>$(fm_get "$spec" name || echo "$slug")</td>"
      echo "<td>$(fm_get "$spec" form || echo '&mdash;')</td>"
      echo "<td><span class=\"badge\">$(fm_get "$spec" status || echo '?')</span></td>"
      echo "<td class=\"num\">$(fm_get "$spec" blanks || echo '&mdash;') / $(fm_get "$spec" blanks_unique || echo '&mdash;')</td>"
      echo "<td class=\"num\">$(fm_get "$spec" coverage || echo '&mdash;')</td>"
    else
      echo "<td colspan=\"5\" class=\"empty\">no spec.md</td>"
    fi

    echo "<td>"
    site_artefact_links "$target" "$slug" "$dir"
    echo "</td>"
    echo "</tr>"
    count=$((count + 1))
  done < <(each_drop_asset "$target")

  if [[ "$count" -eq 0 ]]; then
    echo "<tr><td colspan=\"7\" class=\"empty\">no assets yet</td></tr>"
  fi

  echo "</tbody></table>"
}

site_artefact_links() {
  local target="$1"
  local slug="$2"
  local dir="$3"
  local file name any=0

  while IFS= read -r file; do
    if [[ -z "$file" ]]; then continue; fi
    name="$(basename "$file")"
    # The path is URL-encoded only for spaces, which is the one character the
    # built artefacts actually use. Anything more would need a real encoder, and
    # a filename needing one is a signal about the filename.
    echo "<a href=\"../assets/$slug/${name// /%20}\">$name</a><br>"
    any=1
  done < <(each_artefact_file "$dir")

  if [[ "$any" -eq 0 ]]; then
    echo "<span class=\"empty\">spec only</span>"
  fi
}

site_notes() {
  local target="$1"
  local file any=0

  if [[ ! -d "$target/notes" ]]; then
    return 0
  fi

  echo "<h2>Notes</h2>"
  echo "<p class=\"note\">Durable thinking that is not an asset.</p>"
  echo "<ul>"
  while IFS= read -r file; do
    if [[ -z "$file" ]]; then continue; fi
    echo "<li><a href=\"../notes/$(basename "$file")\">$(basename "$file")</a></li>"
    any=1
  done < <(find "$target/notes" -maxdepth 1 -type f -name '*.md' 2>/dev/null | sort)
  if [[ "$any" -eq 0 ]]; then
    echo "<li class=\"empty\">none</li>"
  fi
  echo "</ul>"
}

# ============================================================================
# SERVE
# ============================================================================

# Rooted at the target, not at site/, so the relative links from the generated
# page out to ../assets/<slug>/ resolve. A server rooted at site/ would render
# the index and then 404 every artefact on it.
serve_site() {
  local target="$1"
  local port="$2"

  require_command python3 "pre-installed on macOS" || return 1

  info "serving $target on http://localhost:$port/site/"
  info "ctrl-c to stop"
  echo ""

  python3 -m http.server "$port" --directory "$target"
}
