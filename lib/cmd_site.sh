#!/usr/bin/env bash
#
# cdtempl site - stand up the microsite over the target
#
# Independent of the application the designs relate to, and knows nothing about
# Phoenix, Ash or Laksa. It serves what is in the target and no more. That
# confinement is what lets the microsite stay independent of the application it
# describes -- the target is the as-designed record, and this is a window onto
# it, not onto the build.
#
# It generates into $CDTEMPL_TARGET/site/, which is deliberately NOT one of the
# paths a drop owns. That is the whole reason the owned-path list exists: a
# generated site sitting in the target survives the next drop instead of being
# deleted by it.
#
# The generated page declares itself generated in a comment on line one, so it is
# exempt from the colour check by the same declaration rule every vendored
# runtime uses. Nothing here is a special case.
#

CDTEMPL_SITE_PORT_DEFAULT="8080"

cmd_site() {
  local flag_target=""
  local port="$CDTEMPL_SITE_PORT_DEFAULT"
  local serve=1

  while [[ $# -gt 0 ]]; do
    case "$1" in
      --target)
        if [[ -z "${2:-}" ]]; then
          error "--target requires a path"
          return 2
        fi
        flag_target="$2"
        shift 2
        ;;
      --port)
        if [[ -z "${2:-}" ]]; then
          error "--port requires a number"
          return 2
        fi
        port="$2"
        shift 2
        ;;
      --build)
        serve=0
        shift
        ;;
      -h|--help)
        show_help site
        return 0
        ;;
      *)
        error "unknown option: $1"
        return 2
        ;;
    esac
  done

  local target source
  target="$(resolve_target "$flag_target" "$PWD")" || return 2
  source="$(target_source "$flag_target" "$PWD")" || return 2

  describe_target "$target" "$source" "$PWD"
  echo ""

  if ! drop_looks_valid "$target"; then
    error "no drop at $target -- expected assets/ or kit/ underneath it"
    return 2
  fi

  mkdir -p "$target/site" || {
    error "could not create $target/site"
    return 1
  }

  build_site "$target" | atomic_write "$target/site/index.html" || return 1
  success "site built at $target/site/index.html"

  if [[ "$serve" -eq 0 ]]; then
    return 0
  fi

  serve_site "$target" "$port"
}

# ============================================================================
# BUILD
# ============================================================================

build_site() {
  local target="$1"
  local venture round

  venture="$(fm_get "$target/index.md" venture 2>/dev/null || basename "$target")"
  round="$(fm_get "$target/index.md" round 2>/dev/null || echo '')"

  echo "<!-- @generated by cdtempl site. Do not edit; rebuild with 'cdtempl site'. -->"
  echo "<!doctype html>"
  echo "<html lang=\"en\"><head>"
  echo "<meta charset=\"utf-8\">"
  echo "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
  echo "<title>$venture -- design record</title>"
  site_style
  echo "</head><body>"
  echo "<main>"

  echo "<header>"
  echo "<h1>$venture</h1>"
  if [[ -n "$round" ]]; then
    echo "<p class=\"meta\">Round $round &middot; the as-designed record</p>"
  else
    echo "<p class=\"meta\">the as-designed record</p>"
  fi
  echo "<p class=\"note\">This is what was <em>designed</em>. The application holds what"
  echo "was <em>built</em>. Keeping them apart is the point: you can hold one against"
  echo "the other and see where implementation diverged from intent.</p>"
  echo "</header>"

  site_documents "$target"
  site_assets "$target"
  site_notes "$target"

  echo "</main>"
  echo "</body></html>"
}

# Greyscale only, and every value is a kit ramp step. The site describes a
